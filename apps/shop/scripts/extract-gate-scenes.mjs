// Copies the account gate's SVG scenes out of the approved mock into a
// generated module (never redraw them). Re-run if the mock changes:
//   node scripts/extract-gate-scenes.mjs ../../../aura-protocols-private/docs/superpowers/specs/2026-10-04-account-gate-mocks/gate-final.html
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) { console.error("usage: node scripts/extract-gate-scenes.mjs <gate-final.html>"); process.exit(1); }
const lines = readFileSync(src, "utf8").split(/\r?\n/);

// A scene starts on its `<svg class="scene …">` line and ends at the next line
// that is only `</svg>` (the nested vial <svg>s close on their own long lines).
function grab(startRe, from = 0) {
  const i = lines.findIndex((l, k) => k >= from && startRe.test(l));
  if (i < 0) throw new Error(`scene start not found: ${startRe}`);
  const j = lines.findIndex((l, k) => k > i && /^\s*<\/svg>\s*$/.test(l));
  if (j < 0) throw new Error(`scene end not found after line ${i + 1}`);
  return { svg: lines.slice(i, j + 1).join("\n").trim(), end: j };
}

const desk = [];
let at = 0;
for (let n = 0; n < 3; n++) { const r = grab(/<svg class="scene s-desk"/, at); desk.push(r.svg); at = r.end + 1; }
const strip = grab(/<svg class="scene s-ph"/).svg;
const mini = grab(/<svg class="scene m-p"/).svg;

const out = `// GENERATED by scripts/extract-gate-scenes.mjs from the approved account-gate mock
// (private repo docs/superpowers/specs/2026-10-04-account-gate-mocks/gate-final.html). Do not edit.
export const DESK_SCENES: readonly string[] = ${JSON.stringify(desk)};
export const PHONE_STRIP: string = ${JSON.stringify(strip)};
export const PHONE_MINI: string = ${JSON.stringify(mini)};
`;
writeFileSync(new URL("../src/components/store/gate/scenes.generated.ts", import.meta.url), out);
console.log(`wrote 3 desktop scenes + 2 phone strips (${(out.length / 1024).toFixed(0)} KB)`);
