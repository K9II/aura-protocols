const CAS_RE = /^\d{2,7}-\d{2}-\d$/;

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) return null;
  return res.json();
}

async function lookup(name) {
  const base = "https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name";
  const props = await getJson(`${base}/${encodeURIComponent(name)}/property/MolecularFormula,MolecularWeight/JSON`);
  const p = props?.PropertyTable?.Properties?.[0];
  if (!p) return null;
  const syn = await getJson(`https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/${p.CID}/synonyms/JSON`);
  const cas = syn?.InformationList?.Information?.[0]?.Synonym?.find((s) => CAS_RE.test(s));
  return {
    cas,
    formula: p.MolecularFormula,
    molecularWeight: `${Number(p.MolecularWeight).toFixed(1)} g/mol`,
    source: `https://pubchem.ncbi.nlm.nih.gov/compound/${p.CID}`,
  };
}

const out = {};
const missing = [];
for (const [slug, name] of Object.entries(QUERIES)) {
  if (OVERRIDES[slug]) { out[slug] = OVERRIDES[slug]; continue; }
  const r = await lookup(name);
  if (!r || !r.cas) missing.push(`${slug} (${name})${r ? " — no CAS in synonyms" : " — not found"}`);
  if (r) out[slug] = r;
  await new Promise((res) => setTimeout(res, 250)); // PubChem asks for <5 req/s
}

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "src", "data", "catalog-identity.ts");
writeFileSync(
  target,
  `// GENERATED by scripts/fetch-identity.mjs — do not edit by hand.\n` +
  `// Re-run the script; put non-PubChem values in its OVERRIDES with a source URL.\n` +
  `import type { Identity } from "./catalog";\n\n` +
  `export const IDENTITY: Record<string, Identity> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(out).length} identities -> ${target}`);
if (missing.length) {
  console.error(`\nNEEDS A CITED OVERRIDE (${missing.length}):\n  ${missing.join("\n  ")}`);
  process.exitCode = 1;
}
