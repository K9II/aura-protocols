-- supabase/inquiries.sql
-- Admin command center, part 7: Inquiries. Two-way threads: /contact and
-- /wholesale open an inquiry; owner replies go out by email (SES) with a
-- per-thread Reply-To (r-<token>@in.auraprotocols.com); customer replies come
-- back through SES receiving (lib/inquiries/inbound.ts) into inquiry_messages.
-- Run after storefront.sql, accounts-checkout.sql and today.sql. Idempotent.
-- RLS on, no policies: service role only.

-- ---------- 1. inquiries: one row per conversation ----------
